"""burau_sage.py: exact checks of the monodromy inputs for d = 4, 5, 6 (Sage, exact cyclotomic arithmetic).
Model (McMullen, Braid groups and Hodge theory, Thm 4.1): for the curve y^d = (x - b_1)...(x - b_n), n = d, and
q = zeta_d^(-k) (1 <= k <= d-1), H^1(X)_q is spanned by e_1..e_n (indices mod n) with
   <e_i, e_i> = 2 Im q,  <e_i, e_{i+1}> = sqrt(-1) (1 - q),  <e_i, e_j> = 0 otherwise,
(McMullen's form is conjugate-linear in the first slot; in our convention <x, y> = x^T G conj(y) this reads
 <e_i, e_{i+1}> = -sqrt(-1)(1 - q), and then sum e_j and sum q^j e_j span the radical, as in his proof of Thm 4.1;
 with the other sign the radical sits at the eigenvalues -1, -conj(q) of the rotation, which exist only for even n)
and the twists act by  x -> x - (q+1) <x, e_i>/<e_i, e_i> e_i  (q != -1),  x -> x - (sqrt(-1)/2) <x, e_i> e_i  (q = -1).
We work on C^n with this hermitian Gram matrix, take the quotient E by its radical and check, for every (d, k):
  (a) the T_i preserve the form, satisfy the braid relations (cyclic indices) and fix the radical;
  (b) dim E = d - 2 and the signature of the form on E is (k - 1, d - 1 - k) (McMullen Cor. 3.2);
  (c) the algebra generated by T_1..T_{n-1} on E is all of M_{d-2} (absolute irreducibility);
  (d) if some Galois conjugate k' = u k (u a unit mod d) has 2 <= k' <= d-2 (indefinite form): a word w in the T_i and an
      embedding sigma with |sigma(tr w)| > d - 2, so w has infinite order (finite order => |trace| <= dim under every
      embedding); for q = -1 also: T_1 - I is nonzero and nilpotent;
  (e) if every conjugate is definite: the order of the group generated by T_1..T_{n-1} on E (GAP), expected 96 (d = 4)
      and 155520 (d = 6).
usage: sage -python burau_sage.py   (SageMath 10.10; GAP for the group orders)
"""
import json, itertools, time
from sage.all import (CyclotomicField, matrix, identity_matrix, vector, lcm, gcd, CIF, ComplexIntervalField,
                      MatrixGroup, ZZ)

T0 = time.time()


def model(d, k):
    n = d
    N = lcm(4, d)
    K = CyclotomicField(N)
    z = K.gen()
    zd, I = z ** (N // d), z ** (N // 4)
    q = zd ** (-k)
    conj = lambda a: a.conjugate()
    imq = (q - conj(q)) / (2 * I)
    G = matrix(K, n, n)
    for j in range(n):
        G[j, j] = 2 * imq
        G[j, (j + 1) % n] += -I * (1 - q)              # McMullen's sqrt(-1)(1 - q), in the convention <x, y> = x^T G conj(y)
        G[(j + 1) % n, j] += conj(-I * (1 - q))
    assert G == G.transpose().apply_map(conj)
    Ts = []
    for i in range(n):
        ei = vector(K, [1 if j == i else 0 for j in range(n)])
        row = G.column(i)                          # <x, e_i> = sum_j x_j G[j, i]
        if q != -1:
            coef = (q + 1) / G[i, i]
        else:
            coef = I / 2
        T = identity_matrix(K, n) - coef * matrix(K, n, 1, list(ei)) * matrix(K, 1, n, list(row))
        Ts.append(T)
    return K, z, q, G, Ts


def quotient(K, G, Ts):
    n = G.nrows()
    Nb = G.transpose().right_kernel().basis_matrix()   # x with x^T G = 0: radical
    r = Nb.nrows()
    # complement: coordinate vectors not in the span
    B = []
    for j in range(n):
        cand = matrix(K, B + [[1 if i == j else 0 for i in range(n)]])
        if matrix(K, list(cand.rows()) + list(Nb.rows())).rank() == len(B) + 1 + r:
            B.append([1 if i == j else 0 for i in range(n)])
        if len(B) == n - r:
            break
    M = matrix(K, B + list(Nb.rows())).transpose()      # columns: complement basis, then radical basis
    Mi = M.inverse()
    m = n - r
    As = []
    for T in Ts:
        X = Mi * T * M
        assert X.submatrix(0, m, m, r) == 0             # radical invariant
        As.append(X.submatrix(0, 0, m, m))
    Bm = matrix(K, B).transpose()
    GE = Bm.transpose() * G * Bm.apply_map(lambda a: a.conjugate())
    return m, r, As, GE


def signature(K, H):
    """exact hermitian LDL* with pivoting; signs of the (real) pivots by interval arithmetic"""
    H = copy_matrix(H)
    m = H.nrows()
    pos = neg = 0
    idx = list(range(m))
    while idx:
        piv = next((i for i in idx if H[i, i] != 0), None)
        if piv is None:
            # all diagonal zero: combine two indices
            i, j = next(((i, j) for i in idx for j in idx if i < j and H[i, j] != 0), (None, None))
            if i is None:
                break
            # replace e_i by e_i + c e_j with c chosen to make the diagonal nonzero
            for c in (K(1), K.gen(), K.gen() ** 2, K(-1)):
                val = H[i, i] + c * H[j, i] + c.conjugate() * H[i, j] + c * c.conjugate() * H[j, j]
                if val != 0:
                    break
            P = identity_matrix(K, m)                    # basis change e_i -> e_i + c e_j (congruence P^T H conj(P))
            P[j, i] = c
            H = P.transpose() * H * P.apply_map(lambda a: a.conjugate())
            continue
        p = H[piv, piv]
        s = CIF(p).real()
        assert not s.contains_zero(), 'pivot sign undecided'
        if s > 0:
            pos += 1
        else:
            neg += 1
        for i in idx:
            if i != piv and H[i, piv] != 0:
                f = H[i, piv] / p
                for j in idx:
                    H[i, j] -= f * H[piv, j]
        for i in idx:
            if i != piv:
                H[piv, i] = 0
        idx.remove(piv)
    return pos, neg


def copy_matrix(H):
    return matrix(H.base_ring(), H.nrows(), H.ncols(), list(H.list()))


def algebra_dim(K, As):
    m = As[0].nrows()
    span = []                                      # rows: flattened matrices
    def add(M):
        v = list(M.list())
        cand = matrix(K, span + [v])
        if cand.rank() > len(span):
            span.append(v)
            return True
        return False
    frontier = [identity_matrix(K, m)]
    add(frontier[0])
    while frontier:
        new = []
        for M in frontier:
            for A in As:
                P = M * A
                if add(P):
                    new.append(P)
        frontier = new
        if len(span) == m * m:
            break
    return len(span)


def infinite_order_witness(K, z, As, dim, maxlen=5, maxwords=200000):
    gens = [(('T%d' % (i + 1)), A) for i, A in enumerate(As)] + \
           [(('T%d^-1' % (i + 1)), A.inverse()) for i, A in enumerate(As)]
    embs = K.embeddings(ComplexIntervalField(200))
    count = 0
    for L in range(1, maxlen + 1):
        for word in itertools.product(range(len(gens)), repeat=L):
            count += 1
            if count > maxwords:
                return None
            M = identity_matrix(K, dim)
            for w in word:
                M = M * gens[w][1]
            t = M.trace()
            for e in embs:
                if (e(t).abs() - dim).lower() > 0:
                    return dict(word='*'.join(gens[w][0] for w in word), trace=str(t), embedding=str(e.im_gens()[0]),
                                abs_trace_lower=float(e(t).abs().lower()))
    return None


def main():
    out = []
    for d in (4, 5, 6):
        for k in range(1, d):
            t0 = time.time()
            K, z, q, G, Ts = model(d, k)
            n = d
            ok_form = all(T.transpose() * G * T.apply_map(lambda a: a.conjugate()) == G for T in Ts)
            ok_braid = all(Ts[i] * Ts[(i + 1) % n] * Ts[i] == Ts[(i + 1) % n] * Ts[i] * Ts[(i + 1) % n] for i in range(n)) \
                and all(Ts[i] * Ts[j] == Ts[j] * Ts[i] for i in range(n) for j in range(n)
                        if (i - j) % n not in (0, 1, n - 1))
            m, r, As, GE = quotient(K, G, Ts[:n - 1])
            u1 = vector(K, [1] * n)
            uq = vector(K, [q ** j for j in range(n)])
            rad_ok = (r == 2 and u1 * G == 0 and uq * G == 0)      # radical = span(sum e_j, sum q^j e_j)
            sig = signature(K, GE)
            units = [u for u in range(1, d) if gcd(u, d) == 1]
            conj = sorted(set((u * k) % d for u in units))
            indefinite_conj = [c for c in conj if 2 <= c <= d - 2]
            alg = algebra_dim(K, As)
            res = dict(d=d, k=k, q='zeta_%d^-%d' % (d, k), form_preserved=ok_form, braid_relations=ok_braid,
                       dim_E=m, radical_dim=r, radical_is_span_sum_e_and_sum_q_e=bool(rad_ok), signature=sig, expected_signature=(k - 1, d - 1 - k),
                       signature_ok=(tuple(sig) == (k - 1, d - 1 - k)), algebra_dim=alg,
                       absolutely_irreducible=(alg == m * m), galois_conjugates=conj,
                       indefinite_conjugates=indefinite_conj)
            if indefinite_conj:
                res['infinite_order_witness'] = infinite_order_witness(K, z, As, m)
                if q == -1:
                    N1 = As[0] - identity_matrix(K, m)
                    res['transvection_nilpotent_nonzero'] = bool(N1 != 0 and N1 * N1 == 0)
            else:
                res['group_order'] = int(MatrixGroup(As).order())
            res['seconds'] = round(time.time() - t0, 1)
            out.append(res)
            print(json.dumps(res), flush=True)
    json.dump(out, open('burau_sage.json', 'w'), indent=1, default=str)


if __name__ == '__main__':
    main()
